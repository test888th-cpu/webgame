#!/usr/bin/env python3
"""Imports the HD-2D street kit: separately painted pieces (buildings, shops,
vehicles, props, animals, ground tiles) that the game assembles into each
area's scenery.

  python3 tools/assets/kit_import.py

The project owner paints each piece on a flat green backdrop with a dark
outline, like the characters. art/kit/kit.json lists the pieces: the source
image in art/kit/src/, how tall the piece stands in game pixels, and which
layer it belongs to. For every piece this script

  * keys out the backdrop: green connected to the image border goes, so green
    inside the outline (a pharmacy cross, a glass bottle) stays; strong green
    enclosed by the piece (between wires, chair legs) goes too unless the piece
    says "keep_green";
  * drops stray blobs (specks; with "haze", the warm glow some backdrops
    have in a corner, which pieces lit warm all over must not use);
  * removes the green fringe at the edge, trims, and scales the piece to HD:
    `hd` texture pixels per game pixel, drawn scaled down so it stays sharp
    at any window size;

and writes client/assets/kit/<piece>.png. Ground tiles are cropped instead
of keyed and mirrored so they repeat without a seam. Then it lays out every
area of client/data/areas.json from its theme in kit.json, deterministically
from the area id, and records pieces and layouts in the manifest's "kit"
section, which Scenery.gd builds from. The sky stays generated by
gen_environment.py.
"""

from __future__ import annotations

import hashlib
import json
import random
import sys
from collections import deque
from pathlib import Path

from PIL import Image, ImageChops, ImageFilter

ROOT = Path(__file__).resolve().parents[2]
KIT = ROOT / "art" / "kit"
SPEC = KIT / "kit.json"
AREAS = ROOT / "client" / "data" / "areas.json"
OUT = ROOT / "client" / "assets" / "kit"
MANIFEST = ROOT / "client" / "assets" / "manifest.json"

# Keying works on a copy no longer than this, which is plenty for pieces at
# most a few hundred texture pixels tall and keeps the pure-Python fills quick.
WORK_SIZE = 1000
# Green beating red and blue by this much is backdrop when it touches the
# border; by HOLE_MARGIN it is backdrop even when the piece encloses it.
KEY_MARGIN = 40
HOLE_MARGIN = 95
GLOW_MARGIN = 40
GLOW_BRIGHT = 150
# Blobs smaller than this share of the piece are specks of the backdrop.
SPECK_SHARE = 0.004
# The piece itself is at least this big next to the largest blob (a corner
# glow on the backdrop can be bigger than a slim lamp post).
MAIN_SHARE = 0.1

# Where things stand, in game pixels (see ZoneSim.LANE_TOP = 250).
BUILDING_FEET = 232
POST_FEET = 248
KERB = 250
VIEW_W = 640
VIEW_H = 360


class KitError(Exception):
    pass


def seeded(area_id: str, salt: str) -> random.Random:
    digest = hashlib.sha256(f"{area_id}:{salt}".encode()).hexdigest()
    return random.Random(int(digest[:16], 16))


def fractions_box(size: tuple[int, int], crop: list[float] | None) -> tuple[int, int, int, int]:
    if not crop:
        return (0, 0, size[0], size[1])
    return (round(crop[0] * size[0]), round(crop[1] * size[1]), round(crop[2] * size[0]), round(crop[3] * size[1]))


def green_spill(image: Image.Image) -> Image.Image:
    """How much each pixel's green beats its red and blue (0 when it does not)."""
    r, g, b = image.split()
    return ImageChops.subtract(g, ImageChops.lighter(r, b))


def components(cells: bytearray, w: int, h: int) -> list[list[int]]:
    """8-connected groups of the cells set to 1."""
    seen = bytearray(len(cells))
    groups = []
    for start in range(len(cells)):
        if not cells[start] or seen[start]:
            continue
        seen[start] = 1
        group = [start]
        queue = deque([start])
        while queue:
            i = queue.popleft()
            x, y = i % w, i // w
            for dy in (-1, 0, 1):
                ny = y + dy
                if ny < 0 or ny >= h:
                    continue
                for dx in (-1, 0, 1):
                    nx = x + dx
                    if 0 <= nx < w:
                        j = ny * w + nx
                        if cells[j] and not seen[j]:
                            seen[j] = 1
                            group.append(j)
                            queue.append(j)
        groups.append(group)
    return groups


def warm_glow(image: Image.Image) -> bytes:
    """255 where a pixel is the bright warm haze some backdrops have in a
    corner (orange fading into the green): red and green both well above
    blue. The pieces' dark outline never is, so a fill through it stops there."""
    r, g, b = image.split()
    warm = ImageChops.darker(ImageChops.subtract(r, b), ImageChops.subtract(g, b))
    bright = ImageChops.darker(r, g)
    return ImageChops.multiply(
        warm.point(lambda v: 255 if v >= GLOW_MARGIN else 0),
        bright.point(lambda v: 255 if v >= GLOW_BRIGHT else 0),
    ).tobytes()


def backdrop(spill: bytes, glow: bytes, w: int, h: int) -> bytearray:
    """1 for the green (and warm haze) connected to the image border (4-connected)."""
    out = bytearray(w * h)
    queue = deque()
    for x in range(w):
        queue.extend((x, (h - 1) * w + x))
    for y in range(h):
        queue.extend((y * w, y * w + w - 1))
    while queue:
        i = queue.popleft()
        if out[i] or (spill[i] < KEY_MARGIN and not glow[i]):
            continue
        out[i] = 1
        x, y = i % w, i // w
        if x > 0:
            queue.append(i - 1)
        if x < w - 1:
            queue.append(i + 1)
        if y > 0:
            queue.append(i - w)
        if y < h - 1:
            queue.append(i + w)
    return out


def cut_out(source: Image.Image, piece: dict) -> Image.Image:
    """The piece on a transparent background, trimmed, at working size."""
    image = source.convert("RGB").crop(fractions_box(source.size, piece.get("crop")))
    image.thumbnail((WORK_SIZE, WORK_SIZE), Image.LANCZOS)
    w, h = image.size
    spill = green_spill(image).tobytes()
    haze = warm_glow(image) if piece.get("haze", False) else bytes(w * h)
    gone = backdrop(spill, haze, w, h)
    if not piece.get("keep_green", False):
        hole = piece.get("hole_margin", HOLE_MARGIN)
        for i, value in enumerate(spill):
            if value >= hole:
                gone[i] = 1
    solid = bytearray(1 - v for v in gone)
    groups = components(solid, w, h)
    total = sum(len(g) for g in groups)
    edges = piece.get("edges", False)
    touching = [any(i % w in (0, w - 1) or i // w in (0, h - 1) for i in g) for g in groups]
    # The piece is the largest blob clear of the border; a blob touching the
    # border is glow on the backdrop, unless nothing else is left (a sign
    # hanging from the top edge).
    largest = max(groups, key=len, default=[])
    inside = max((g for g, t in zip(groups, touching) if not t), key=len, default=[])
    main = inside if len(inside) >= len(largest) * MAIN_SHARE else largest
    for group, touches in zip(groups, touching):
        if group is main:
            continue
        if len(group) < total * SPECK_SHARE or (touches and not edges):
            for i in group:
                solid[i] = 0
    mask = Image.frombytes("L", (w, h), bytes(solid)).point(lambda v: 255 if v else 0)
    # Shave the one-pixel fringe where the outline blends into the green,
    # then pull the green spill out of what is left along the edge.
    mask = mask.filter(ImageFilter.MinFilter(3))
    edge = ImageChops.subtract(mask, mask.filter(ImageFilter.MinFilter(5)))
    r, g, b = image.split()
    despilled = ImageChops.darker(g, ImageChops.lighter(r, b))
    # "despill" pulls the green out everywhere: glass that shows the backdrop.
    g = despilled if piece.get("despill", False) else Image.composite(despilled, g, edge)
    out = Image.merge("RGBA", (r, g, b, mask))
    box = mask.getbbox()
    if box is None:
        raise KitError("nothing left after keying")
    return out.crop(box)


def hd_resize(image: Image.Image, height: int) -> Image.Image:
    """Premultiplied resampling, so the transparent edge does not darken."""
    width = max(1, round(image.width * height / image.height))
    return image.convert("RGBa").resize((width, height), Image.LANCZOS).convert("RGBA")


def tile(source: Image.Image, piece: dict, hd: int) -> Image.Image:
    """A ground strip: cropped, scaled, and mirrored so its ends meet."""
    image = source.convert("RGB").crop(fractions_box(source.size, piece.get("crop")))
    strip = hd_resize(image.convert("RGBA"), piece["height"] * hd)
    seamless = Image.new("RGBA", (strip.width * 2, strip.height))
    seamless.paste(strip, (0, 0))
    seamless.paste(strip.transpose(Image.FLIP_LEFT_RIGHT), (strip.width, 0))
    return seamless


def make_piece(piece_id: str, piece: dict, hd: int) -> Image.Image:
    with Image.open(KIT / "src" / piece["file"]) as opened:
        source = opened.copy()
    if piece.get("tile", False):
        return tile(source, piece, hd)
    cut = cut_out(source, piece)
    image = hd_resize(cut, piece["height"] * hd)
    if piece.get("mirror", False):
        mirrored = Image.new("RGBA", (image.width * 2, image.height))
        mirrored.paste(image, (0, 0))
        mirrored.paste(image.transpose(Image.FLIP_LEFT_RIGHT), (image.width, 0))
        image = mirrored
    return image


def source_digest(piece: dict) -> str:
    data = (KIT / "src" / piece["file"]).read_bytes()
    recipe = json.dumps(piece, sort_keys=True).encode()
    return hashlib.sha256(data + recipe).hexdigest()[:16]


# ------------------------------------------------------------------ layout


def game_width(pieces: dict, piece_id: str) -> float:
    return pieces[piece_id]["size"][0] / pieces[piece_id]["hd"]


def pick(rng: random.Random, weighted: dict[str, float], avoid: str = "") -> str:
    names = [n for n in sorted(weighted) if n != avoid] or sorted(weighted)
    return rng.choices(names, [weighted[n] for n in names])[0]


def row(rng: random.Random, pieces: dict, pool: dict, start: float, end: float, gap: list[int], layer: str, feet: int) -> list[dict]:
    """Pieces side by side from `start` to `end`, never the same one twice running."""
    placed = []
    x = start
    last = ""
    while x < end:
        piece_id = pick(rng, pool, last)
        w = game_width(pieces, piece_id)
        placed.append({"piece": piece_id, "layer": layer, "x": round(x + w / 2), "y": feet})
        x += w + rng.randint(gap[0], gap[1])
        last = piece_id
    return placed


def track_span(width: int, scroll: float) -> tuple[int, int]:
    """Where the elevated track runs in its layer: past both edges of the view
    wherever the camera goes."""
    return (round(VIEW_W / 2 * scroll - VIEW_W / 2) - 40, round((width - VIEW_W / 2) * scroll + VIEW_W / 2) + 40)


def lay_out(area_id: str, area: dict, theme: dict, pieces: dict, scrolls: dict) -> list[dict]:
    """Deterministic placements for one area. x is the piece's centre and y
    its foot line, in the coordinates of the piece's layer (a layer scrolling
    at s covers 320s - 320 .. (width - 320)s + 320 as the camera moves)."""
    rng = seeded(area_id, "kit")
    width = int(area["width"])
    placed: list[dict] = []
    s = scrolls["back"]
    placed += row(rng, pieces, theme["back"], -80, (width - VIEW_W / 2) * s + VIEW_W / 2 + 40, theme["back_gap"], "back", BUILDING_FEET)
    if theme.get("track"):
        # Trains stand on the elevated track, which runs unbroken (see track_span).
        span = track_span(width, scrolls["track"])
        x = span[0] + rng.randint(0, 200)
        train_w = game_width(pieces, theme["train"])
        while x < span[1]:
            placed.append({"piece": theme["train"], "layer": "track", "x": round(x + train_w / 2), "y": theme["track_top"] + 1})
            x += train_w + rng.randint(*theme["train_gap"])
    placed += row(rng, pieces, theme["front"], rng.randint(-40, -10), width + 40, theme["front_gap"], "front", BUILDING_FEET)

    # Lamp posts and poles at a steady rhythm; small props in between.
    posts = []
    x = rng.randint(60, 110)
    while x < width - 30:
        posts.append({"piece": pick(rng, theme["posts"]), "layer": "sidewalk", "x": x, "y": POST_FEET})
        x += rng.randint(*theme["post_gap"])
    taken = [(p["x"] - 12, p["x"] + 12) for p in posts]
    # Nothing tall stands right behind an NPC, where it would be hidden.
    taken += [(npc["x"] - 22, npc["x"] + 22) for npc in area.get("npcs", [])]
    props = []
    x = 30
    while x < width - 40:
        x += rng.randint(*theme["prop_gap"])
        piece_id = pick(rng, theme["props"])
        half = game_width(pieces, piece_id) / 2
        span = (x - half - 4, x + half + 4)
        if any(span[0] < b and a < span[1] for a, b in taken):
            continue
        taken.append(span)
        props.append({"piece": piece_id, "layer": "sidewalk", "x": x, "y": rng.randint(240, 246)})
    # Parked at the kerb, clear of the area's ends so exits stay readable.
    vehicles = []
    parked: list[tuple[float, float]] = []
    count = rng.randint(*theme["vehicles_count"]) if theme.get("vehicles") else 0
    for _ in range(count * 4):
        if len(vehicles) >= count:
            break
        piece_id = pick(rng, theme["vehicles"])
        half = game_width(pieces, piece_id) / 2
        x = rng.randint(int(80 + half), int(width - 80 - half))
        if any(x - half - 30 < b and a < x + half + 30 for a, b in parked):
            continue
        parked.append((x - half, x + half))
        vehicles.append({"piece": piece_id, "layer": "street", "x": x, "y": KERB + 4})
    placed += sorted(posts + props, key=lambda p: (p["y"], p["x"]))
    placed += sorted(vehicles, key=lambda p: p["x"])
    if theme.get("foreground"):
        s = scrolls["fg"]
        x = rng.randint(200, 400)
        while x < (width - VIEW_W / 2) * s + VIEW_W / 2:
            placed.append({"piece": pick(rng, theme["foreground"]), "layer": "fg", "x": x, "y": VIEW_H + 14})
            x += rng.randint(*theme["fg_gap"])
    return placed


# -------------------------------------------------------------------- main


def build_pieces(spec: dict, only_changed: dict | None = None) -> dict:
    hd = int(spec["hd"])
    OUT.mkdir(parents=True, exist_ok=True)
    out = {}
    for piece_id, piece in sorted(spec["pieces"].items()):
        digest = source_digest(piece)
        path = OUT / f"{piece_id}.png"
        previous = (only_changed or {}).get(piece_id, {})
        if previous.get("digest") == digest and path.exists():
            with Image.open(path) as saved:
                size = list(saved.size)
        else:
            try:
                image = make_piece(piece_id, piece, hd)
            except KitError as error:
                raise KitError(f"{piece_id}: {error}") from error
            image.save(path, optimize=True)
            size = list(image.size)
            print(f"cut {piece_id} {size[0]}x{size[1]}")
        entry = {"file": f"res://assets/kit/{piece_id}.png", "size": size, "hd": hd, "digest": digest}
        for key in ("glow", "tile"):
            if key in piece:
                entry[key] = piece[key]
        out[piece_id] = entry
    return out


def lay_out_all(spec: dict, pieces: dict) -> dict:
    areas = json.loads(AREAS.read_text())["areas"]
    out = {}
    for area_id, area in sorted(areas.items()):
        theme_id = area.get("theme", "market")
        theme = spec["themes"][theme_id]
        out[area_id] = {
            "theme": theme_id,
            "width": int(area["width"]),
            "tint": theme.get("tint", {}),
            "ground": theme["ground"],
            "far": theme["far"],
            "placed": lay_out(area_id, area, theme, pieces, spec["scroll"]),
        }
        if theme.get("track"):
            start, end = track_span(int(area["width"]), spec["scroll"]["track"])
            out[area_id]["track"] = {"piece": theme["track"], "top": theme["track_top"], "from": start, "to": end}
    return out


def main() -> int:
    spec = json.loads(SPEC.read_text())
    manifest = json.loads(MANIFEST.read_text())
    previous = manifest.get("kit", {}).get("pieces", {})
    force = "--force" in sys.argv
    try:
        pieces = build_pieces(spec, None if force else previous)
    except (KitError, OSError, KeyError) as error:
        print(f"FAILED: {error}", file=sys.stderr)
        return 1
    manifest["kit"] = {
        "credits": spec["credits"],
        "scroll": spec["scroll"],
        "pieces": pieces,
        "areas": lay_out_all(spec, pieces),
    }
    MANIFEST.write_text(json.dumps(manifest, indent=2, sort_keys=True) + "\n")
    print(f"kit: {len(pieces)} pieces, {len(manifest['kit']['areas'])} areas")
    return 0


if __name__ == "__main__":
    sys.exit(main())
