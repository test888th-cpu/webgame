#!/usr/bin/env python3
"""Renders the reference-side catalogs from the indexes in data/reference/.

  python3 tools/content/render_reference_catalog.py

Inputs:
- data/reference/woc_abilities_index.json and woc_content_index.json (text scans
  of World of ClaudeCraft at a pinned commit; see their "source" block);
- client/data/rpg_reference.json (the nine classes and their kits);
- client/data/skills.json and data/content_audit.json (the game's current
  skills and items).

Writes docs/SKILL_DATABASE_CATALOG.md and docs/EQUIPMENT_AND_RARITY_CATALOG.md.
Nothing is invented: a value the scan did not find is shown as "?".
"""

from __future__ import annotations

import collections
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]


def load(rel: str) -> dict:
    return json.loads((ROOT / rel).read_text())


def esc(v: object) -> str:
    return "?" if v is None else str(v).replace("|", "\\|")


def skills() -> str:
    abil = load("data/reference/woc_abilities_index.json")
    src = abil["source"]
    index = abil["abilities"]
    classes = load("client/data/rpg_reference.json")["classes"]
    ours = load("client/data/skills.json")["skills"]
    lines = [
        "# Skill database catalog", "",
        "Generated by `tools/content/render_reference_catalog.py`; do not edit by hand.", "",
        f"**Reference:** World of ClaudeCraft `{src['commit'][:8]}`, {src['method']}.",
        "Display names here are the reference's own and **must not ship**",
        "(docs/NAMING_FRAMEWORK.md). Original names come with the naming batches.",
        "",
        "## Status",
        "",
        "| | Count | Status |",
        "|---|---:|---|",
        f"| Reference ability records (all files) | {len(index)} | VERIFIED by source scan |",
        f"| Reference class-kit abilities (nine classes) | {sum(len(c['abilities']) for c in classes.values())} | VERIFIED by source scan |",
        "| Reference abilities implemented in the game | 0 | NOT IMPLEMENTED: the class/skill system is Phase 3–4 of the adoption |",
        f"| Current game skills (legacy, five heroes' jobs) | {len(ours)} | LEGACY: to be replaced, see CONTENT_COMPLETENESS_AUDIT.md |",
        "",
        "Talents: each class chooses a spec at level 5 and then one of 3 options in each of",
        "6 rows (levels 5, 8, 11, 14, 17, 20), so 18 options per class",
        "(`src/sim/content/talent_rows.ts`, `choice_rows.ts`). Spec-locked abilities are",
        "listed with their specs below.",
        "",
    ]
    for cls, data in classes.items():
        kit = data["abilities"]
        lines += [f"## {data['name']} ({len(kit)} kit abilities, resource: {data['resource']})", "",
                  "| Reference id | Learn Lv | Cost | Cast | Cooldown | Range | School | Specs | Passive | Ranks | Effects |",
                  "|---|---:|---:|---:|---:|---:|---|---|---|---|---|"]
        for aid in kit:
            a = index.get(aid)
            if a is None:
                lines.append(f"| `{aid}` | ? | ? | ? | ? | ? | ? | ? | ? | ? | not parsed by the scan |")
                continue
            ranks = "; ".join(f"r{r[0]} Lv {r[1]}" for r in (a.get("ranks") or []))
            lines.append(
                f"| `{aid}` | {esc(a['learn'])} | {esc(a['cost'])} | {esc(a['cast'])} | {esc(a['cd'])} |"
                f" {esc(a['range'])} | {esc(a['school'])} | {esc(', '.join(a['specs']) if a['specs'] else '-')} |"
                f" {'yes' if a['passive'] else '-'} | {ranks or '-'} | {esc(', '.join(a['effects'] or []))} |")
        lines.append("")
    lines += ["## Current game skills (legacy)", "", "| Id | Name | Job / hero |", "|---|---|---|"]
    for sid, s in sorted(ours.items()):
        lines.append(f"| `{sid}` | {esc(s.get('name', ''))} | {esc(s.get('job', s.get('hero', '')))} |")
    return "\n".join(lines) + "\n"


def equipment() -> str:
    ref = load("data/reference/woc_content_index.json")
    items = ref["items"]
    audit = load("data/content_audit.json")["items"]
    slot_ref = collections.Counter(v["slot"] for v in items.values() if v["slot"])
    qual_ref = collections.Counter(v["quality"] for v in items.values() if v["quality"])
    kind_ref = collections.Counter(v["kind"] for v in items.values())
    slot_ours = collections.Counter(v["slot"] for v in audit.values() if v["slot"])
    rar_ours = collections.Counter(v["rarity"] for v in audit.values() if v["rarity"])
    lines = [
        "# Equipment and rarity catalog", "",
        "Generated by `tools/content/render_reference_catalog.py`; do not edit by hand.",
        "Reference counts are a source scan (lower bounds; generated records are not seen).",
        "",
        "## Slots",
        "",
        "The reference has 13 equipment slots in `EQUIP_SLOTS`: mainhand, offhand, helmet,",
        "neck, shoulder, chest, waist, legs, gloves, feet, ring1, ring2, trinket. Items",
        "name `ring` for both ring slots. The current game has 6 slots.",
        "",
        "| Reference slot | Reference items | Current game slot | Current items |",
        "|---|---:|---|---:|",
    ]
    mapping = {"mainhand": "weapon", "helmet": "head", "chest": "body", "gloves": "hands", "feet": "feet",
               "ring": "charm", "neck": "-", "shoulder": "-", "waist": "-", "legs": "-", "offhand": "-", "trinket": "-"}
    for slot, n in slot_ref.most_common():
        ours = mapping.get(slot, "-")
        lines.append(f"| {slot} | {n} | {ours} | {slot_ours.get(ours, 0) if ours != '-' else '-'} |")
    lines += ["", "The mapping above is only a comparison; no slot migration has been made.", "",
              "## Rarity", "", "| Reference quality | Items | | Current rarity | Items |", "|---|---:|---|---|---:|"]
    rq = qual_ref.most_common(); rr = rar_ours.most_common()
    for i in range(max(len(rq), len(rr))):
        a = rq[i] if i < len(rq) else ("", "")
        b = rr[i] if i < len(rr) else ("", "")
        lines.append(f"| {a[0]} | {a[1]} | | {b[0]} | {b[1]} |")
    lines += ["", "`godforged` exists only in the current game (an owner decision is pending on how",
              "it is represented).", "", "## Reference item kinds", "", "| Kind | Items |", "|---|---:|"]
    for kind, n in kind_ref.most_common():
        lines.append(f"| {kind} | {n} |")
    return "\n".join(lines) + "\n"


def main() -> int:
    for name, text in (("SKILL_DATABASE_CATALOG.md", skills()), ("EQUIPMENT_AND_RARITY_CATALOG.md", equipment())):
        (ROOT / "docs" / name).write_text(text, encoding="utf-8")
        print(f"wrote docs/{name} ({len(text.splitlines())} lines)")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
