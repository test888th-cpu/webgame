#!/usr/bin/env python3
"""Perturbation evidence for the approximated Math audit.

  python3 tools/content/audit_math_perturbation.py --ref <checkout> [--check]

ECMAScript leaves Math.sin, cos, atan2, acos, tan, hypot, pow (and the like) to the
engine, so V8 may return a different last bit than this evaluator. The builder
proves by taint tracking that no approximated result reaches a registry value and
that every decision on one stays inside a reviewed binding
(reference_content.CONFINED_BINDINGS). This tool adds empirical evidence: it
rebuilds every registry with each approximated call site's results changed, and
compares the registries byte for byte with the normal build.

Modes per site: one ulp up, one ulp down (the engines' real uncertainty), and a
gross change (x 1.5 + 0.25) that flips every branch taken on the value. Plus all
sites together, one ulp up and one ulp down. The registries compared are every
builder output except the manifest, which records the audit itself.

Writes data/registry/math_perturbation_audit.json; --check reruns and compares.
Nothing from the reference is executed (the builder's static evaluator only).
"""

from __future__ import annotations

import argparse
import hashlib
import json
import math
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
import build_reference_registries as b  # noqa: E402

OUT = b.REGISTRY / "math_perturbation_audit.json"


def digest(outputs: dict) -> dict[str, str]:
    return {str(p.relative_to(b.ROOT)): hashlib.sha256(t.encode()).hexdigest()
            for p, t in sorted(outputs.items()) if p != b.MANIFEST_OUT}


def nudge(mode: str):
    def f(_site, value):
        x = float(value)
        if not math.isfinite(x):
            return x
        if mode == "up":
            return math.nextafter(x, math.inf)
        if mode == "down":
            return math.nextafter(x, -math.inf)
        return x * 1.5 + 0.25
    return f


def run(checkout: Path) -> dict:
    base_outputs = b.build(checkout)
    base = digest(base_outputs)
    manifest = json.loads(base_outputs[b.MANIFEST_OUT])
    sites = [s["site"] for s in manifest["math_audit"]["sites"]]

    def trial(target, mode) -> str:
        inner = nudge(mode)
        hook = (lambda site, v: inner(site, v) if site == target else v) if target else inner
        try:
            got = digest(b.build(checkout, perturb=hook))
        except SystemExit as e:
            return f"build stopped: {str(e).splitlines()[0][:160]}"
        changed = sorted(k for k in base if got.get(k) != base[k])
        return "identical" if not changed else "CHANGED: " + ", ".join(changed)

    per_site = {s: {m: trial(s, m) for m in ("up", "down", "gross")} for s in sites}
    together = {m: trial(None, m) for m in ("up", "down")}
    ulp_ok = all(r[m] == "identical" for r in per_site.values() for m in ("up", "down")) and \
        all(v == "identical" for v in together.values())
    return {
        "_comment": "Generated by tools/content/audit_math_perturbation.py. Each approximated Math call site's results were changed (one ulp up, one ulp down, and grossly) and every registry rebuilt; 'identical' means all registry outputs are byte-identical to the normal build. Do not edit.",
        "commit": b.COMMIT,
        "registries_compared": sorted(base),
        "baseline_sha256": base,
        "sites": per_site,
        "all_sites_together": together,
        "conclusion": ("no registry output changes when any approximated result moves by one ulp, alone or together"
                       if ulp_ok else "a registry output depends on an approximated result: see the CHANGED entries"),
    }


def main(argv: list[str]) -> int:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--ref", required=True, type=Path)
    ap.add_argument("--check", action="store_true")
    args = ap.parse_args(argv[1:])
    text = json.dumps(run(args.ref), indent=1, sort_keys=True) + "\n"
    if args.check:
        same = OUT.exists() and OUT.read_text(encoding="utf-8") == text
        print("math perturbation audit is current" if same else f"stale: {OUT.relative_to(b.ROOT)}")
        return 0 if same else 1
    OUT.write_text(text, encoding="utf-8")
    print("wrote", OUT.relative_to(b.ROOT))
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv))
