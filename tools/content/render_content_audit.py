#!/usr/bin/env python3
"""Renders the content audit documents from the JSON the Godot harness writes.

  godot --headless --path client --script res://tests/harness/ContentAudit.gd \\
      -- --out=$PWD/data/content_audit.json
  python3 tools/content/render_content_audit.py data/content_audit.json

Every number comes from that report, which the game's own rules produced
(LootIndex, EnhanceRules, ContentDB); nothing here re-implements a game rule
(tools/CLAUDE.md). The only arithmetic is presentation: 1/p and the chance of at
least one drop in N tries, 1 - (1 - p)^N, for independent per-kill chances.

Writes docs/DROP_RATE_AUDIT.md, docs/ITEM_DATABASE_CATALOG.md,
docs/MONSTER_BOSS_DROP_CATALOG.md and docs/ENHANCEMENT_BALANCE_AUDIT.md.
"""

from __future__ import annotations

import json
import math
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
DOCS = ROOT / "docs"
HEADER = (
    "Generated by `tools/content/render_content_audit.py` from the report of"
    " `client/tests/harness/ContentAudit.gd` (the game's own rules: LootIndex,"
    " EnhanceRules, ContentDB); do not edit by hand."
)
HOW = {
    "loot": "own loot table",
    "catalog": "catalog drop table",
    "boss_list": "boss's own list",
    "ground": "farming ground",
    "elite": "field elite",
    "tier": "world-boss tier",
    "kill": "world-boss kill",
}


def pct(p: float) -> str:
    if p >= 1.0:
        return "100% (guaranteed)"
    if p >= 0.01:
        return f"{p * 100:.2f}%"
    return f"{p * 100:.4f}%"


def tries(p: float, target: float) -> str:
    if p <= 0:
        return "never"
    if p >= 1:
        return "1"
    return str(math.ceil(math.log(1 - target) / math.log(1 - p)))


def esc(text: object) -> str:
    return str(text).replace("|", "\\|").replace("\n", " ")


def drop_rows(report: dict) -> list[dict]:
    rows = []
    for enemy_id, enemy in report["enemies"].items():
        places = sorted({p["area"] for p in enemy["places"]}) or ["(no area)"]
        for drop in enemy["drops"]:
            item = report["items"].get(drop["item"], {})
            area = drop["area"] or ", ".join(places)
            rows.append({
                "area": area, "enemy": enemy_id, "enemy_name": enemy["name"], "kind": enemy["kind"],
                "item": drop["item"], "item_name": item.get("name", "?"), "rarity": item.get("rarity", ""),
                "chance": float(drop["chance"]), "qty": drop["quantity"], "how": drop["how"],
                "condition": drop["condition"], "pity": drop["pity"], "steps": drop["steps"],
            })
    rows.sort(key=lambda r: (r["area"], r["enemy"], -r["chance"], r["item"]))
    return rows


def drop_rate_audit(report: dict) -> str:
    rows = drop_rows(report)
    rare = sorted((r for r in rows if r["chance"] < 0.05), key=lambda r: r["chance"])
    lines = [
        "# Drop rate audit", "", HEADER, "",
        "**What a chance means here:** the probability per kill (or per reward) that the",
        "item drops at least once, as the game rolls it. LootIndex works it out from the",
        "rules that pay the drop, so it is never typed by hand:",
        "",
        "- **own loot table:** an independent roll per entry. Entries marked *pity*",
        "  start at this chance and rise per earlier defeat until the hero has one",
        "  (LootRules).",
        "- **catalog drop table:** a weighted selection. A roll happens at the table's",
        "  chance, then a category, a grade and an item are picked. The figure shown is",
        "  the resulting chance for this item, and these chances do not sum to 100%.",
        "- **farming ground** and **field elite:** a scaled roll on the ground's own table.",
        "- **world-boss tier** and **world-boss kill:** personal rewards.",
        "",
        "**Expected kills** for an independent chance p is 1/p. That is an average, not a",
        "promise: after 1/p kills about 63% of players have the item.",
        "",
        f"**Totals:** {len(rows)} drop paths over {len(report['enemies'])} enemies,",
        f"{len({r['item'] for r in rows})} distinct items.",
        "",
        "## Reference status",
        "",
        "These are **the game's current (legacy) drop rates, verified against its own",
        "rules.** They are **not** World of ClaudeCraft's drop tables.",
        "",
        "- The reference rolls each mob's `loot` entries independently (`chance` 0..1).",
        "  Entries sharing a `rollGroup` are exclusive, and quest drops are gated by",
        "  `questId` (`src/sim/types.ts` LootEntry).",
        "- Our enemies are not the reference's mobs, so none of these rates is",
        "  REFERENCE-VERIFIED. See CONTENT_COMPLETENESS_AUDIT.md.",
        "",
        "## Rare drops (under 5% per kill): what to expect",
        "",
        "| Item | Rarity | From | Area | Chance | Expected kills | 50% after | 90% after | 99% after | Notes |",
        "|---|---|---|---|---:|---:|---:|---:|---:|---|",
    ]
    for r in rare:
        note = "pity: rises until owned" if r["pity"] else esc(r["condition"])
        lines.append(
            f"| {esc(r['item_name'])} (`{r['item']}`) | {r['rarity']} | {esc(r['enemy_name'])} ({r['kind']}) |"
            f" {esc(r['area'])} | {pct(r['chance'])} | {1 / r['chance']:.0f} | {tries(r['chance'], 0.5)} |"
            f" {tries(r['chance'], 0.9)} | {tries(r['chance'], 0.99)} | {note} |")
    lines += ["", "## Selected drops: the steps multiply out to the chance", "",
              "A catalog drop is a weighted selection. Per roll, its chance is roll chance ×",
              "category share × grade share × item share, and over n rolls it is",
              "1 − (1 − per-roll)^n. Every catalog path below was re-multiplied from the steps",
              "LootIndex reports, and must equal its chance.", ""]
    checked = bad = 0
    for r in rows:
        st = r["steps"]
        if not st or "grade_share" not in st:
            continue
        per_roll = st["roll_chance"] * st["category_share"] * st["grade_share"] * st["item_share"]
        expect = 1 - (1 - per_roll) ** int(st.get("rolls", 1))
        checked += 1
        if abs(expect - r["chance"]) > 1e-9:
            bad += 1
    lines.append(f"**{checked} selected-drop paths checked, {bad} mismatches.**")
    if bad:
        raise SystemExit(f"{bad} catalog chances do not match their steps")
    lines += ["", "## Every drop path", "",
              "| Area | Monster / boss | Kind | Item | Rarity | Chance | Quantity | How | Conditions |",
              "|---|---|---|---|---|---:|---|---|---|"]
    for r in rows:
        cond = "; ".join(x for x in (esc(r["condition"]), "pity" if r["pity"] else "") if x)
        lines.append(
            f"| {esc(r['area'])} | {esc(r['enemy_name'])} (`{r['enemy']}`) | {r['kind']} |"
            f" {esc(r['item_name'])} (`{r['item']}`) | {r['rarity']} | {pct(r['chance'])} |"
            f" {r['qty'][0]}-{r['qty'][1]} | {HOW.get(r['how'], r['how'])} | {cond or '-'} |")
    return "\n".join(lines) + "\n"


def item_catalog(report: dict) -> str:
    items = report["items"]
    lines = [
        "# Item database catalog (current game)", "", HEADER, "",
        f"{len(items)} items: {sum(1 for v in items.values() if not v['catalog'])} in"
        f" `items.json` and {sum(1 for v in items.values() if v['catalog'])} in `item_catalog.json`.",
        "Every one has at least one source; the content audit fails otherwise.",
        "",
        "These are the game's current items: not World of ClaudeCraft items, so not",
        "reference-verified. The reference inventory is in CONTENT_COMPLETENESS_AUDIT.md.",
        "",
        "| Id | Name | Type | Slot | Rarity | Level | Price | Stats | Sources |",
        "|---|---|---|---|---|---:|---:|---|---|",
    ]
    for item_id, v in sorted(items.items()):
        kinds = sorted({s["kind"] for s in v["sources"]} | ({"starter kit"} if v["starter"] else set()))
        stats = ", ".join(f"{k} {v['stats'][k]}" for k in sorted(v["stats"])) if isinstance(v["stats"], dict) else ""
        lines.append(
            f"| `{item_id}` | {esc(v['name'])} | {v['type'] or v['category']} | {v['slot'] or '-'} |"
            f" {v['rarity']} | {v['level'] or '-'} | {v['price']} | {esc(stats) or '-'} |"
            f" {', '.join(kinds)} ({len(v['sources'])}) |")
    return "\n".join(lines) + "\n"


def monster_catalog(report: dict) -> str:
    lines = [
        "# Monster and boss drop catalog (current game)", "", HEADER, "",
        "| Id | Name | Kind | Max HP | XP | Coins | Areas (how it appears) | Drop paths | Guaranteed |",
        "|---|---|---|---:|---:|---|---|---:|---:|",
    ]
    for enemy_id, e in sorted(report["enemies"].items(), key=lambda kv: (kv[1]["kind"], kv[0])):
        places = ", ".join(f"{p['area']} ({p['how']})" for p in e["places"]) or "-"
        lines.append(
            f"| `{enemy_id}` | {esc(e['name'])} | {e['kind']} | {e['max_hp']} | {e['xp']} |"
            f" {e['money'][0]}-{e['money'][1]} | {esc(places)} | {len(e['drops'])} |"
            f" {sum(1 for d in e['drops'] if d['guaranteed'])} |")
    return "\n".join(lines) + "\n"


def enhancement_audit(report: dict) -> str:
    enh = report["enhance"]
    lines = [
        "# Enhancement (upgrade) audit", "", HEADER, "",
        "## Status: LEGACY system, not reference data",
        "",
        "The workbench upgrade (+0 to +{0}) is the game's own system (`EnhanceRules`,".format(enh["max"]),
        "`progression.json` \"enhance\"). It is **not** World of ClaudeCraft's.",
        "",
        "**Correction to earlier reports:** the reference **does** have an equipment",
        "upgrade, the **Rift Forge**. Its rules, read in source at `d2b91e08`:",
        "",
        "- **Gear:** only Rift gear (bands from Rift clears; `src/sim/rift/progression.ts`).",
        "- **Steps:** at most **5** (`RIFT_BAND_MAX_UPGRADE = 5`, `src/sim/rift/band_ladder.ts`).",
        "- **Cost:** `rift_essence` per step, **2, 4, 6, 8, 10** (`riftUpgradeCost = 2 + 2 x level`).",
        "- **Odds:** **always succeeds**; no failure, downgrade or destruction.",
        "- **Effect:** each step raises the item level by 1, and stats are rebuilt from the",
        "  band ladder.",
        "- **Gems:** sockets are a separate action.",
        "",
        "Choosing between the two is an owner decision (CONTENT_COMPLETENESS_AUDIT.md §5).",
        "The table below is what the game does **today**.",
        "",
        f"## Implemented values (bonus +{enh['bonus_per_level'] * 100:.0f}% of the item's positive stats per level)",
        "",
        "| Level | Success rate | Expected tries | Coins (item Lv 1 / 51 / 61) | Materials (item Lv 1) | Stat bonus at this level | On failure |",
        "|---:|---:|---:|---|---|---:|---|",
    ]
    total_coins = 0.0
    for row in enh["levels"]:
        c = row["cost"]
        expected = 1 / row["rate"] if row["rate"] > 0 else float("inf")
        total_coins += c["1"]["coins"] * expected
        mats = ", ".join(f"{k} x{v}" for k, v in c["1"]["items"].items())
        lines.append(
            f"| +{row['to']} | {row['rate'] * 100:.0f}% | {expected:.2f} |"
            f" {c['1']['coins']} / {c['51']['coins']} / {c['61']['coins']} | {mats} |"
            f" +{row['to'] * enh['bonus_per_level'] * 100:.0f}% | item and level kept; cost spent |")
    lines += [
        "",
        f"**Expected coins from +0 to +{enh['max']}** on an item of level 1 (every try pays):",
        f"about {total_coins:.0f}. Each level costs its price times 1/rate on average; failures",
        "do not raise the next chance (the owner's rule, `EnhanceRules`).",
        "",
        "## Power gap",
        "",
        f"A +{enh['max']} item gives {enh['max'] * enh['bonus_per_level'] * 100:.0f}% more of its positive stats",
        "than the same item at +0. The reference's Rift Forge adds at most 5 item levels,",
        "and only to Rift gear.",
        "",
    ]
    return "\n".join(lines)


def main(argv: list[str]) -> int:
    if len(argv) != 2:
        print(__doc__)
        return 2
    report = json.loads(Path(argv[1]).read_text())
    outputs = {
        "DROP_RATE_AUDIT.md": drop_rate_audit(report),
        "ITEM_DATABASE_CATALOG.md": item_catalog(report),
        "MONSTER_BOSS_DROP_CATALOG.md": monster_catalog(report),
        "ENHANCEMENT_BALANCE_AUDIT.md": enhancement_audit(report),
    }
    for name, text in outputs.items():
        (DOCS / name).write_text(text, encoding="utf-8")
        print(f"wrote docs/{name} ({len(text.splitlines())} lines)")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv))
