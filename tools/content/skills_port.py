"""The skills port's evidence register (docs/SKILLS_PORT.md).

build_runtime_pack.py classifies every ability. An ability runs in the game only when
everything it touches is ported to client/sim:
* each effect type is a runEffects arm the runtime has, and each field the ability's
  effects use is one that arm reads (EFFECT_FIELDS);
* each aura kind it applies has every consumer ported (AURA_KINDS);
* each definition field it carries is read by the cast rules (DEF_KEYS);
* each reference behaviour file that names its id is either ported (PORTED, with the
  GDScript that carries it) or audited as not changing its behaviour (NOT_BEHAVIOUR).

Nothing here is a rule: it is the record of which reference code has a port, kept beside
the builder so the status of every ability is computed, never asserted by hand.
"""

